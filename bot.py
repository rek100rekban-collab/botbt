# ========== MAIN ==========
def main():
    token = os.getenv("TELEGRAM_BOT_TOKEN")
    if not token:
        logger.error("❌ TELEGRAM_BOT_TOKEN не задан в Variables!")
        raise RuntimeError("TELEGRAM_BOT_TOKEN не задан в Variables!")

    app = Application.builder().token(token).build()
    
    # Регистрация всех команд
    app.add_handler(CommandHandler("start", start))
    app.add_handler(CommandHandler("prize", prize))
    app.add_handler(CommandHandler("howplaying", howplaying))
    app.add_handler(CommandHandler("support", support))
    app.add_handler(CommandHandler("winterauction", winterauction))

    logger.info("✅ Бот запущен — ждём команды")
    app.run_polling()

if __name__ == "__main__":
    main()
