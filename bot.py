# ==================================================
# ФОНОВАЯ ЗАДАЧА: РАССЫЛКА КАЖДЫЕ 23 ЧАСА
# ==================================================
async def daily_case_reminder(context: ContextTypes.DEFAULT_TYPE):
    """Отправляет напоминание всем пользователям каждые 23 часа"""
    while True:
        await asyncio.sleep(23 * 3600)  # СПИМ 23 ЧАСА (не блокирует бота!)
        logger.info("🔔 Начинаю ежедневную рассылку...")
        for user_id in list(user_ids):  # КОПИРУЕМ список, чтобы избежать ошибок при изменении во время итерации
            try:
                await context.bot.send_message(
                    chat_id=user_id,
                    text="⚡️Твой кейс «Ежедневный 🗓️» уже перезарядился! Забирай его скорее, пока награда не сгорела на проекте STEP BY STEP🔥!"
                )
            except Exception as e:
                logger.error(f"❌ Не удалось отправить напоминание {user_id}: {e}")

# ==================================================
# ЗАПУСК БОТА + ФОНОВАЯ ЗАДАЧА
# ==================================================
def main():
    token = os.getenv("TELEGRAM_BOT_TOKEN")
    if not token:
        logger.error("❌ TELEGRAM_BOT_TOKEN не задан в Variables!")
        raise RuntimeError("TELEGRAM_BOT_TOKEN не задан в Variables!")

    app = Application.builder().token(token).build()

    # Регистрация 6 команд
    app.add_handler(CommandHandler("start", start))
    app.add_handler(CommandHandler("prize", prize))
    app.add_handler(CommandHandler("howplaying", howplaying))
    app.add_handler(CommandHandler("support", support))
    app.add_handler(CommandHandler("geraklgame", geraklgame))
    app.add_handler(CommandHandler("event", event))

    # ЗАПУСКАЕМ ФОНОВУЮ ЗАДАЧУ РАССЫЛКИ
    job_queue = app.job_queue
    job_queue.run_once(lambda _: asyncio.create_task(daily_case_reminder(app)), 0)  # Старт через 0 секунд

    logger.info("✅ Бот и рассылка запущены — ждём команды...")
    app.run_polling()

if __name__ == "__main__":
    main()
