# ========== РАССЫЛКА КАЖДЫЕ 23 ЧАСА ==========
async def daily_broadcast(context: ContextTypes.DEFAULT_TYPE):
    """Отправляет сообщение всем пользователям из списка"""
    users = load_users()
    message = ("⚡️ Твой кейс «Ежедневный 🗓️» уже перезарядился! "
               "Забирай его скорее, пока награда не сгорела на проекте STEP BY STEP 🔥!")
    
    success = 0
    failed = 0
    
    for user_id in users:
        try:
            await context.bot.send_message(chat_id=user_id, text=message)
            success += 1
            logger.info(f"✅ Сощение отправлено пользователю {user_id}")
        except Exception as e:
            failed += 1
            logger.error(f"❌ Ошибка отправки пользователю {user_id}: {e}")
    
    logger.info(f"📢 Рассылка завершена: успешно={success}, ошибки={failed}")

# ========== MAIN ==========
def main():
    token = os.getenv("TELEGRAM_BOT_TOKEN")
    if not token:
        logger.error("❌ TELEGRAM_BOT_TOKEN не задан в Variables!")
        raise RuntimeError("TELEGRAM_BOT_TOKEN не задан в Variables!")

    app = Application.builder().token(token).build()
    
    # Регистрация команд
    app.add_handler(CommandHandler("start", start))
    app.add_handler(CommandHandler("prize", prize))
    app.add_handler(CommandHandler("howplaying", howplaying))
    app.add_handler(CommandHandler("support", support))
    app.add_handler(CommandHandler("geraklgame", geraklgame))
    app.add_handler(CommandHandler("event", event))
    
    # Запускаем рассылку каждые 23 часа
    # job_queue доступен через bot
    app.job_queue.run_repeating(daily_broadcast, interval=23*60*60, first=10)
    
    logger.info("✅ Бот запущен — рассылка каждые 23 часа")
    app.run_polling()

if __name__ == "__main__":
    main()
